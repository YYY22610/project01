_STRUCTURED_SPEAK = """\
【发言格式（必须遵守，按下方 Markdown 模板）】
- 用 **1 个大标题**开头（emoji + 主题 + 副标题），如 `🌅 黄金时刻首选 | 西湖南线-湖山光影带`
- 大标题下方写**一行元信息**（安全性/距离/时段/光线/风格等），如 `安全系数 ⭐⭐⭐⭐⭐ | 全栈道/石板路 | 下午3:30-19:00 光线封神`
- 再列 2-4 个具体项目，每条严格按格式：
  **项目名**（限定/方式）：¥XX/人 或 免费，描述（地点+方式+卖点+时段+光线+来源）
  示例：**雷峰塔（登塔观日落）**：¥40/人，需预约（"杭州西湖风景名胜区"公众号），塔内空调+落地窗西向，完美框住净慈寺黄墙+夕照山剪影；登顶后步行5分钟至夕照亭，纯平拍机位（景区官网）
- 不同领域用一行 `---` 隔开（不要用 `##` 标题）
- 总长 100~200 字；不要替其他角色发言；需要回应他人用 @对方 一句带过
- 可选：如要把这条归并到右侧临时规划，可在条目末尾附【xxx】标签（如【景点游览】【餐饮安排】【交通方式】【住宿选择】【预算明细】），不附也不影响展示\
"""


def build_persona_system(p: dict) -> str:
    """职能角色 system prompt：只谈自己职责领域，短发言，不套完整方案模板 FORMAT_SPEC。

    注意：不再拼接 FORMAT_SPEC（那是主持人整合时才用的完整方案格式），
    否则每个专家都会输出一份完整方案，导致右侧栏信息过载、角色发言混乱。
    """
    scope = _ROLE_SCOPES.get(p["id"], "")
    return (
        p["prefix"] + "\n\n" + discussion_rules(p["peers"]) + "\n\n"
        + scope + "\n\n" + _STRUCTURED_SPEAK
    )


